import { expect, test } from "@playwright/test";

test("plugin installation, account connection, health and removal use the selected agent", async ({ page }) => {
  await page.route(/^https:\/\/api\.github\.com\//, (route) => route.fulfill({ status: 404, body: "{}" }));
  await page.addInitScript(() => localStorage.setItem("supercharge-studio/v1", JSON.stringify({ settings: { bind: "127.0.0.1:2456", secret: "e2e", transport: "ws", autoStart: false, alwaysApprove: false }, groups: [{ id: "g", name: "Personal", projects: [{ id: "p", name: "demo", cwd: "/tmp", chats: [] }] }], activeProjectId: "p" })));
  await page.goto("/");
  await expect(page.locator(".status")).toHaveText("open");
  await page.locator(".composer textarea").fill("/plugins");
  await page.locator(".composer textarea").press("Enter");
  await expect(page.getByRole("heading", { name: "Available plugins" })).toBeVisible();
  await expect(page.getByLabel("Catalog URL", { exact: true })).toHaveValue("https://www.superchargeai.in/api/plugins/v1");
  await page.getByLabel("Catalog URL", { exact: true }).fill("https://catalog.example/api/plugins/v1");
  await page.getByLabel("Private catalog read token", { exact: true }).fill("fixture-catalog-token-never-persist");
  await page.getByRole("button", { name: "Connect catalog", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Catalog settings saved on this agent.");
  await expect(page.getByLabel("Private catalog read token", { exact: true })).toHaveValue("");
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain("fixture-catalog-token-never-persist");
  await page.getByRole("button", { name: "Review installation" }).first().click();
  await page.getByRole("button", { name: "Install package", exact: true }).click();
  const installed = page.locator(".card").filter({ has: page.getByRole("button", { name: "Enable", exact: true }) });
  await expect(installed).toContainText("github");
  await installed.getByRole("button", { name: "Enable", exact: true }).click();
  await page.getByRole("button", { name: "Enable reviewed plugin" }).click();
  await expect(installed).toHaveCount(0);
  await page.getByTestId("tools-connections").click();
  await expect(page.getByText("ready · 1 tool")).toBeVisible();
  await page.getByLabel("Access token", { exact: true }).fill("fixture-secret-never-persist");
  await page.getByRole("button", { name: "Save and select account" }).click();
  await expect(page.getByLabel("Access token", { exact: true })).toHaveValue("");
  await expect(page.getByText("github · default", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain("fixture-secret-never-persist");
  await expect(page.getByText("ready · 1 tool")).toBeVisible();
  await page.getByRole("combobox", { name: "Authentication", exact: true }).selectOption("oauth");
  await page.getByLabel("OAuth client ID", { exact: true }).fill("fixture-oauth-client");
  await page.getByRole("button", { name: "Save and select account" }).click();
  await page.getByRole("button", { name: "Connect / reconnect" }).click();
  await expect(page.getByRole("status")).toContainText("Account connected.");
  await page.screenshot({ path: "/tmp/supercharge-plugin-connections.png", fullPage: true });
  await page.getByRole("button", { name: "Disconnect", exact: true }).click();
  await expect(page.getByText("github · default", { exact: true })).toHaveCount(0);
  await page.getByTestId("tools-plugins").click();
  await page.getByRole("button", { name: "Disable", exact: true }).click();
  await page.getByRole("button", { name: "Uninstall", exact: true }).click();
  await expect(page.getByText("No plugins found on this agent.")).toBeVisible();
});
